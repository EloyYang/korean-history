// 기출 문장(GICHUL_TOP) → 왕·나라 자동 연결 후보 (사람이 검토해 js/typing/kings.js 의 OVERRIDE 로 바로잡는다)
//   node tools/typing_kings.js            → 후보 목록 출력
global.window = {};
['gichul-ex', 'rulers'].forEach((f) => require('../js/' + f + '.js'));
const T = window.GICHUL_TOP, R = window.RULERS;
const plain = (h) => String(h).replace(/\{\{([^}|]+)(?:\|([^}]*))?\}\}/g, (_, n, l) => l || n).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/\|/g, ' ');
const bi = (s) => { const t = s.replace(/[^가-힣0-9A-Za-z]/g, ''); const o = new Set(); for (let i = 0; i < t.length - 1; i++) o.add(t.slice(i, i + 2)); return o; };
const SKIP_PAREN = /통일 과정|집권자|섭정|무신 집권기|복위|^\d+대$|대통령/;
const aliases = (name) => {
  const base = name.replace(/\s*\(.*?\)\s*/g, ' ').trim();
  const paren = (name.match(/\((.*?)\)/g) || []).map((p) => p.slice(1, -1)).filter((p) => !SKIP_PAREN.test(p));
  return [...new Set([base, ...paren])];
};
const res = {};
for (const era of Object.keys(T)) {
  const rs = R[era] || [];
  const docs = rs.map((r) => bi([r.name, r.key, ...r.items.map(plain)].join(' ')));
  const df = {}; docs.forEach((d) => d.forEach((g) => { df[g] = (df[g] || 0) + 1; }));
  T[era].forEach(([s, c]) => {
    const sb = bi(s), flat = s.replace(/\s/g, '');
    const named = rs.filter((r) => aliases(r.name).some((a) => a.length >= 2 && flat.includes(a.replace(/\s/g, ''))));
    const sc = rs.map((r, i) => { let v = 0; sb.forEach((g) => { if (docs[i].has(g)) v += 1 / df[g]; }); return { v, r }; }).sort((a, b) => b.v - a.v);
    const [a, b] = [sc[0], sc[1] || { v: 0 }];
    let pick = null;
    if (named.length === 1) pick = named[0] === (a && a.r) ? named[0] : null;
    else if (!named.length && a && a.v >= 2 && a.v - b.v >= 1) pick = a.r;
    res[s] = { era, c, pick: pick && pick.name, state: pick && pick.state, top: sc.slice(0, 2).map((x) => x.r.name + ':' + x.v.toFixed(1)).join(' | '), named: named.map((r) => r.name) };
  });
}

